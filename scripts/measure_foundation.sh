#!/usr/bin/env bash
# Produces benchmarks/foundation_metrics.txt: tests, known-answer vector counts,
# binary hardening, binary size, Valgrind, cppcheck, and code size.
#
# Usage (from anywhere; the script resolves the repo root itself):
#   scripts/measure_foundation.sh
#
# Everything runs inside a throwaway ubuntu:24.04 container; nothing is built
# on the host. The repo is mounted read-only and copied to a scratch work
# directory inside the container, so every path in the output is relative.
set -euo pipefail

IMAGE="ubuntu:24.04"
OUT_REL="benchmarks/foundation_metrics.txt"

# ---------------------------------------------------------------------------
# Host side: launch the container and capture the report.
# ---------------------------------------------------------------------------
if [[ "${1:-}" != "--in-container" ]]; then
    cd "$(dirname "$0")/.."
    mkdir -p "$(dirname "$OUT_REL")"
    docker run --rm -v "$PWD":/src:ro "$IMAGE" \
        bash /src/scripts/measure_foundation.sh --in-container \
        | sed 's/\x1b\[[0-9;]*m//g' > "$OUT_REL.tmp"
    mv "$OUT_REL.tmp" "$OUT_REL"
    echo "wrote $OUT_REL ($(wc -l < "$OUT_REL") lines)"
    exit 0
fi

# ---------------------------------------------------------------------------
# Container side
# ---------------------------------------------------------------------------
set +e  # keep measuring after a failure; failures are recorded in the report
exec 2>&1

run() { echo "\$ $*"; eval "$@"; echo "[exit=$?]"; echo; }
hdr() {
    echo
    echo "======================================================================"
    echo "== $*"
    echo "======================================================================"
}

WORK=/work  # fixed container path so output is stable across runs
mkdir -p "$WORK"
cp -r /src/. "$WORK"
cd "$WORK"
rm -rf build build-asan build-rel .venv

echo "# VaultNode foundation metrics"
echo "# Generated by scripts/measure_foundation.sh. Do not edit by hand."

hdr "0. ENVIRONMENT"
echo "date_utc: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
run 'grep PRETTY_NAME /etc/os-release'
run 'uname -m'
apt-get update -qq >/dev/null 2>&1
DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
    build-essential cmake pkg-config libssl-dev libmosquitto-dev nlohmann-json3-dev \
    binutils file valgrind cppcheck cloc checksec >/dev/null 2>&1
echo "apt install exit=$?"
echo
run 'g++ --version | head -1'
run 'cmake --version | head -1'
run 'valgrind --version'
run 'cppcheck --version'
run 'openssl version'

hdr "1a. TESTS: DEFAULT BUILD"
run 'cmake -S . -B build >/dev/null && cmake --build build 2>&1 | tail -3'
run 'ctest --test-dir build --output-on-failure'
run 'build/firmware/vaultnode_tests | tee build/tests_output.txt'

hdr "1b. TESTS: VAULTNODE_SANITIZE=ON (ASan + UBSan + LeakSanitizer)"
run 'cmake -S . -B build-asan -DVAULTNODE_SANITIZE=ON | grep VaultNode && cmake --build build-asan 2>&1 | tail -3'
run 'ctest --test-dir build-asan --output-on-failure'
run 'ASAN_OPTIONS=detect_leaks=1:abort_on_error=1 UBSAN_OPTIONS=halt_on_error=1 build-asan/firmware/vaultnode_tests | tee build-asan/tests_output.txt | tail -1'
run 'grep -o "fsanitize=[a-z,]*" build-asan/compile_commands.json | sort -u'

hdr "1c. TEST COUNT RECONCILIATION"
run 'grep -c "^TEST(" firmware/tests/test_crypto.cpp'
run 'grep -c "^TEST(" firmware/tests/test_build_info.cpp'
run 'grep -h "^TEST(" firmware/tests/*.cpp | wc -l'
run 'grep -c "add_test(" firmware/CMakeLists.txt'

hdr "1d. KNOWN-ANSWER VECTOR CHECKS (assertions against published expected values)"
T=firmware/tests/test_crypto.cpp
fn_body() { awk -v n="$1" '$0 ~ "^TEST\\("n"\\)"{f=1} f{print} f&&/^}/{exit}' "$T"; }
KAT_P6=0
echo "-- PROTOCOL.md section 6: CHECK_EQ assertions against expected values, per test"
for t in protocol_6_1_key_diversification protocol_6_1_encrypted_response_and_mac \
         protocol_6_1_firmware_proof protocol_6_2_signed_commands protocol_6_3_signed_telemetry; do
    c=$(fn_body "$t" | grep -cE 'CHECK_EQ\((hex_encode|hmac_hex|canon)')
    KAT_P6=$((KAT_P6 + c))
    printf "%-45s %s\n" "$t" "$c"
done
echo "(length-only CHECK_EQs are excluded by the regex)"
echo
KAT_RFC=$(fn_body rfc4231_hmac_sha256 | grep -c 'CHECK_EQ(hmac_hex')
KAT_NIST=$(fn_body nist_sp800_38a_aes128_cbc | grep -c 'CHECK_EQ(hex_encode(\*ct).substr(0, 128), nist_ct)')
echo "RFC 4231 HMAC-SHA256 test cases:   $KAT_RFC"
echo "NIST SP 800-38A F.2.1 CBC-AES128:  $KAT_NIST (4-block vector, 64 bytes of ciphertext compared)"
echo "PROTOCOL.md section 6 assertions:  $KAT_P6"
KAT_TOTAL=$((KAT_P6 + KAT_RFC + KAT_NIST))
echo "TOTAL known-answer assertions:     $KAT_TOTAL"
echo "(not counted: hmac_empty_message_ok, a widely published but non-standard vector)"

hdr "2. HARDENING: vaultnode-firmware (default build)"
F=build/firmware/vaultnode-firmware
run "file $F"
run "readelf -h $F | grep Type"
run "readelf -lW $F | grep -E 'GNU_RELRO|GNU_STACK'"
run "readelf -d $F | grep -E 'BIND_NOW|FLAGS'"
run "nm -D $F | grep -E '__stack_chk_fail|_chk@'"
run "grep -oE -- '-fstack-protector-strong|-U_FORTIFY_SOURCE -D_FORTIFY_SOURCE=2|-fPIE' build/compile_commands.json | sort | uniq -c"
if command -v checksec >/dev/null; then
    run "checksec --file=$F"
else
    echo "checksec: NOT AVAILABLE (apt install failed); relying on readelf/nm above"
fi
H_PIE=0; H_RELRO=0; H_NOW=0; H_CANARY=0; H_NX=0; H_FORT=0
readelf -h "$F" | grep -q 'DYN (Position-Independent' && H_PIE=1
readelf -lW "$F" | grep -q GNU_RELRO && readelf -d "$F" | grep -q BIND_NOW && H_RELRO=1
readelf -d "$F" | grep -q BIND_NOW && H_NOW=1
nm -D "$F" | grep -q __stack_chk_fail && H_CANARY=1
readelf -lW "$F" | grep GNU_STACK | grep -qv RWE && H_NX=1
nm -D "$F" | grep -qE '__[a-z_]+_chk@' && H_FORT=1
HARD_TOTAL=$((H_PIE + H_RELRO + H_NOW + H_CANARY + H_NX + H_FORT))
echo "computed: PIE=$H_PIE FullRELRO=$H_RELRO BIND_NOW=$H_NOW canary=$H_CANARY NX=$H_NX FORTIFY=$H_FORT -> $HARD_TOTAL/6"

hdr "3. BINARY SIZE (Release-style build: CMAKE_BUILD_TYPE=Release)"
run 'cmake -S . -B build-rel -DCMAKE_BUILD_TYPE=Release >/dev/null && cmake --build build-rel 2>&1 | tail -1'
R=build-rel/firmware/vaultnode-firmware
cp "$R" build-rel/vaultnode-firmware.stripped && strip build-rel/vaultnode-firmware.stripped
S=build-rel/vaultnode-firmware.stripped
run "stat -c '%n %s bytes' $R $S"
SIZE_U=$(stat -c %s "$R"); SIZE_S=$(stat -c %s "$S")
KB_U=$(awk -v b="$SIZE_U" 'BEGIN{printf "%.1f", b/1024}')
KB_S=$(awk -v b="$SIZE_S" 'BEGIN{printf "%.1f", b/1024}')
echo "unstripped = $KB_U KB, stripped = $KB_S KB (bytes/1024)"
echo
echo "-- vaultnode:: symbols linked into the firmware binary today:"
run "nm -C $R | grep -E ' [TtW] vaultnode::' | sed 's/^[0-9a-f]* //'"

hdr "4. VALGRIND memcheck on vaultnode_tests (NON-sanitized default build)"
echo "-- flags: --leak-check=full --error-exitcode=1 (full valgrind stderr; test stdout discarded)"
valgrind --leak-check=full --error-exitcode=1 build/firmware/vaultnode_tests 2>/tmp/vg.txt >/dev/null
VG_EXIT=$?
echo "valgrind_exit=$VG_EXIT"
sed 's/^==[0-9]*==/==PID==/' /tmp/vg.txt
vg() { grep -E "$1" /tmp/vg.txt | sed -E 's/.*: ([0-9,]+) bytes in ([0-9,]+) blocks.*/\1 bytes in \2 blocks/'; }
VG_DEF=$(vg 'definitely lost:'); VG_IND=$(vg 'indirectly lost:'); VG_POS=$(vg 'possibly lost:')
VG_REACH=$(vg 'still reachable:')
VG_ERR=$(grep -oE 'ERROR SUMMARY: [0-9]+ errors' /tmp/vg.txt | grep -oE '[0-9]+')
echo
echo "-- still-reachable breakdown (--show-leak-kinds=reachable): loss records and allocating frames"
valgrind --leak-check=full --show-leak-kinds=reachable build/firmware/vaultnode_tests 2>/tmp/vg_r.txt >/dev/null
grep 'still reachable in loss record' /tmp/vg_r.txt | sed 's/^==[0-9]*==/==PID==/'
echo
grep -oE 'by 0x[0-9A-F]+: [a-zA-Z_:() ]*(vaultnode::|OPENSSL_|CRYPTO_|EVP_|ERR_)[^(]*' /tmp/vg_r.txt \
    | sed 's/by 0x[0-9A-F]*: //' | sort | uniq -c

hdr "5. CPPCHECK (counts exclude the informational checkersReport summary line)"
cppcheck_run() {
    local label="$1"; shift
    echo "-- $label"
    echo "\$ cppcheck --enable=all --inconclusive --suppress=missingIncludeSystem $* firmware/src firmware/include"
    cppcheck --enable=all --inconclusive --suppress=missingIncludeSystem "$@" \
        --template='{file}:{line}: {severity}: {id}: {message}' \
        firmware/src firmware/include 2>&1 >/dev/null | grep -v checkersReport > "/tmp/cpp_$label.txt"
    cat "/tmp/cpp_$label.txt"
    echo "finding_count=$(grep -c . "/tmp/cpp_$label.txt")"
    echo "by_severity: $(awk -F': ' '{print $2}' "/tmp/cpp_$label.txt" | sort | uniq -c | xargs)"
    echo "by_id:       $(awk -F': ' '{print $3}' "/tmp/cpp_$label.txt" | sort | uniq -c | xargs)"
    echo
}
cppcheck_run a_exact
cppcheck_run b_include -I firmware/include
CPP_A=$(grep -c . /tmp/cpp_a_exact.txt); CPP_B=$(grep -c . /tmp/cpp_b_include.txt)
CPP_A_EW=$(grep -cE ': (error|warning): ' /tmp/cpp_a_exact.txt)
CPP_B_EW=$(grep -cE ': (error|warning): ' /tmp/cpp_b_include.txt)

hdr "6. CODE SIZE"
FILES_CMD='find firmware/src firmware/include firmware/tests -type f \( -name "*.cpp" -o -name "*.hpp" \)'
run "$FILES_CMD | sort"
run 'wc -l $(find firmware/src firmware/include firmware/tests -type f \( -name "*.cpp" -o -name "*.hpp" \) | sort)'
run 'cloc --quiet firmware/src firmware/include firmware/tests'
N_FILES=$(eval "$FILES_CMD" | wc -l)
N_PHYS=$(eval "$FILES_CMD" | xargs cat | wc -l)
N_CODE=$(cloc --quiet --csv firmware/src firmware/include firmware/tests | awk -F, '$2=="SUM"{print $5}')

T_DEF=$(tail -1 build/tests_output.txt); T_ASAN=$(tail -1 build-asan/tests_output.txt)

hdr "7. SUMMARY (computed from the runs above)"
cat <<EOF
tests_default:          $T_DEF
tests_sanitize:         $T_ASAN
  CTest reports 1 test because the binary is registered as a single add_test entry;
  the individual TEST() cases run inside it (see 1c for the per-file breakdown).
kat_assertions:         $KAT_TOTAL = $KAT_P6 (PROTOCOL.md section 6) + $KAT_RFC (RFC 4231) + $KAT_NIST (NIST SP 800-38A)
hardening_verified:     $HARD_TOTAL/6 (PIE, Full RELRO, BIND_NOW, stack canary, NX, FORTIFY)
binary_size_release:    $KB_U KB unstripped ($SIZE_U B), $KB_S KB stripped ($SIZE_S B)
  The firmware binary is currently a stub entry point that does not link the crypto
  module (see the symbol list in 3), so this size is not representative of the final firmware.
valgrind:               exit=$VG_EXIT errors=$VG_ERR definitely=[$VG_DEF] indirectly=[$VG_IND] possibly=[$VG_POS] still_reachable=[$VG_REACH]
  Still-reachable blocks are allocated inside OpenSSL via vaultnode::crypto::hmac_sha256,
  which fetches the HMAC algorithm once (EVP_MAC_fetch) and deliberately keeps it for the
  process lifetime. It is still referenced at exit and has a fixed size: not a leak.
cppcheck_exact:         $CPP_A findings ($CPP_A_EW errors/warnings)
cppcheck_with_include:  $CPP_B findings ($CPP_B_EW errors/warnings)
code_size:              $N_FILES files, $N_PHYS physical lines, $N_CODE code lines (cloc)
EOF
